@bempp.callable(complex=True, parameterized=True)
def plane_wave_trace(x, n, domain_index, result, parameters):
    """E_inc × n for E_inc = p e^{ik d·x}; parameters = (k, d, p)"""
    ph = np.exp(1j * parameters[0] * (x[0] * parameters[1] + x[1] * parameters[2] + x[2] * parameters[3]))
    e0, e1, e2 = parameters[4] * ph, parameters[5] * ph, parameters[6] * ph
    result[0] = e1 * n[2] - e2 * n[1]
    result[1] = e2 * n[0] - e0 * n[2]
    result[2] = e0 * n[1] - e1 * n[0]


def assemble_rows(div, k, rep=None, max_gb=0.5):
    """Rows of the EFIE matrix on div (all of them, or the representatives rep), in OpenCL buffers of at most max_gb"""
    N, l2g = div.global_dof_count, div.local2global
    dense = lambda s: np.asarray(bempp.operators.boundary.maxwell.electric_field(div, div, s, k).weak_form().to_dense())

    def _space(rc):
        in_c = np.zeros(N, bool)
        in_c[rc] = True
        sup = np.nonzero(in_c[l2g].any(axis=1))[0].astype(np.uint32)
        test = bempp.function_space(div.grid, "SNC", 0, support_elements=sup, include_boundary_dofs=False)
        full_of = np.full(test.global_dof_count, -1)
        ok = test.local_multipliers[sup] != 0                   # local functions that are not degrees of freedom have multiplier 0
        full_of[test.local2global[sup][ok]] = l2g[sup][ok]
        rows = np.nonzero(in_c[full_of])[0]
        return test, rows[np.argsort(full_of[rows])]

    test, rows = (bempp.function_space(div.grid, "SNC", 0), slice(None)) if rep is None else _space(rep)
    est_rows = test.global_dof_count
    if 16 * est_rows * N <= max_gb * 2 ** 30:
        return dense(test)[rows]
    del test, rows
    rep = np.arange(N) if rep is None else rep
    A = np.empty((len(rep), N), complex, order="F" if len(rep) == N else "C")
    pos = 0
    for rc in np.array_split(rep, min(len(rep), int(np.ceil(16.0 * est_rows * N / (max_gb * 2 ** 30))) + 1)):
        test, rows = _space(rc)
        A[pos:pos + len(rc)] = dense(test)[rows]
        del test
        pos += len(rc)
    return A


def efie(grid, k, d, p, pts):
    """Plain EFIE solve on any mesh, no symmetry: the field at pts and the number of unknowns"""
    div, curl = bempp.function_space(grid, "RWG", 0), bempp.function_space(grid, "SNC", 0)
    A = assemble_rows(div, k)
    par = np.concatenate(([k], d, p))
    b = bempp.GridFunction(div, fun=plane_wave_trace, dual_space=curl, function_parameters=par).projections(curl)
    J = sla.solve(A, b, overwrite_a=True, check_finite=False)
    return field(div, J, k, pts), div.global_dof_count


def field(div, J, k, pts):
    """Scattered field of the surface current J (RWG coefficients) at pts (P, 3)"""
    lam = bempp.GridFunction(div, coefficients=J)
    # The EFIE with the incident trace on the right gives minus the current, hence the sign
    return -(bempp.operators.potential.maxwell.electric_field(div, np.ascontiguousarray(pts.T), k) * lam).T


# Symmetry

def group(mirrors=(1, 1, 1)):
    """The reflections generated by the mirrors x → -x, y → -y, z → -z that are switched on"""
    return np.array(list(itertools.product(*[((1.0, -1.0) if on else (1.0,)) for on in mirrors])))


def mirror_grid(pts, tris, refl):
    """
    The mesh made of the piece (pts, tris) and its images, ordered by reflection: element e
    of the piece has the image e + r T under reflection number r (T = len(tris))
      Returns the grid, the vertex maps of the reflections, and T
    """
    key, verts, elems = {}, [], []
    for R in refl:
        loc, img = [], pts * R
        for x, kk in zip(img, map(tuple, (np.round(img, 12) + 0.0).tolist())):
            if kk not in key:
                key[kk] = len(verts)
                verts.append(x)
            loc.append(key[kk])
        t = np.array(loc)[tris]
        elems.append(t if np.prod(R) > 0 else t[:, ::-1])
    verts = np.array(verts)
    vmap = np.array([[key[kk] for kk in map(tuple, (np.round(verts * R, 12) + 0.0).tolist())] for R in refl])
    return bempp.Grid(verts.T, np.concatenate(elems).T.astype(np.uint32)), vmap, len(tris)


def action(space, vmap, emap):
    """
    Signed permutations of the RWG functions under symmetries of the mesh, given by the maps of
    the vertices vmap[g, v] and of the elements emap[g, e]: T_g e_j = sgn[g, j] e_perm[g, j]
    """
    grid = space.grid
    ne, N = grid.number_of_elements, space.global_dof_count
    el, vt = grid.elements.T, grid.vertices.T
    cen = vt[el].mean(axis=1)

    def flow(e):
        # For each local function of element e: the local vertex it flows away from, and the sign of the flow
        w = space.evaluate(e, np.array([[1 / 3], [1 / 3]]))[:, :, 0].T
        dv = cen[e][None, :] - vt[el[e]]
        cs = (w @ dv.T) / (np.linalg.norm(w, axis=1)[:, None] * np.linalg.norm(dv, axis=1)[None, :])
        v = np.argmax(np.abs(cs), axis=1)
        return v, np.sign(cs[np.arange(3), v])

    # The library's convention is the same on every element: learn it on one, check it on forty
    mult = np.asarray(space.local_multipliers, float)
    vloc, s0 = flow(0)
    c = s0 * mult[0]
    for e in np.unique(np.linspace(0, ne - 1, 40).astype(int)):
        v, sg = flow(e)
        assert np.array_equal(v, vloc) and np.array_equal(sg, c * mult[e]), "unexpected RWG convention"
    opp, sig = el[:, vloc], c[None, :] * mult

    # Follow each function from the first element that carries it to its image
    l2g = space.local2global
    first = np.full(N, ne)
    np.minimum.at(first, l2g, np.arange(ne)[:, None])
    l = np.argmax(l2g[first] == np.arange(N)[:, None], axis=1)
    perm, sgn = np.zeros((len(vmap), N), np.int32), np.zeros((len(vmap), N), np.int8)
    for q in range(len(vmap)):
        e2, p2 = emap[q][first], vmap[q][opp[first, l]]
        l2 = np.argmax(opp[e2] == p2[:, None], axis=1)
        perm[q], sgn[q] = l2g[e2, l2], sig[first, l] * sig[e2, l2]
    return perm, sgn


@njit(parallel=True, cache=True)
def fold(A, rows, cols, coef):
    """out[i, k] = Σ_r coef[r, k] A[rows[i], cols[r, k]]: F-ordered rows of A against the symmetrised functions"""
    out = np.zeros((cols.shape[1], len(rows)), np.complex128).T
    for i in prange(len(rows)):
        for r in range(cols.shape[0]):
            for k in range(cols.shape[1]):
                out[i, k] += coef[r, k] * A[rows[i], cols[r, k]]
    return out


class Symmetric:
    """
    EFIE on a mesh with symmetries given by maps of its vertices vmap[g, v] and elements emap[g, e].
    The symmetries act on the RWG functions as signed permutations, so only the rows of one
    test function per orbit are assembled; Mirror and Cyclic split a wave into its symmetry classes.
    """
    def __init__(self, grid, vmap, emap, k):
        self.k, self.G = k, len(vmap)
        self.div = div = bempp.function_space(grid, "RWG", 0)
        self.N = div.global_dof_count
        self.perm, self.sgn = action(div, vmap, emap)
        del vmap, emap
        self.rep = np.nonzero(self.perm.min(axis=0) == np.arange(self.N))[0]   # one RWG function per orbit
        t0 = time.time()
        self.A = assemble_rows(div, k, self.rep)
        self.t_assemble = time.time() - t0
        self.curl = bempp.function_space(grid, "SNC", 0)        # all the test functions, for the right-hand side

    def trace(self, d, p):
        """Projections of the incident trace E_inc × n on all the Nédélec test functions"""
        par = np.concatenate(([self.k], d, p))
        return bempp.GridFunction(self.div, fun=plane_wave_trace, dual_space=self.curl, function_parameters=par).projections(self.curl)

    def field(self, J, pts):
        return field(self.div, J, self.k, pts)


class Mirror(Symmetric):
    """
    EFIE on a mesh made by mirror_grid, with the parity classes of the reflections refl.
    The rows of the fundamental piece are assembled once; solve() then takes any wave.
    """
    def __init__(self, grid, vmap, n_piece, refl, k):
        self.refl, self.lu = refl, {}

        # Each element of the piece number r has its image under reflection q in piece number (r times q)
        ne = grid.number_of_elements
        r_of = np.arange(ne) // n_piece                             # the piece of each element
        idx = {tuple(R): i for i, R in enumerate(refl)}
        emap = []
        for Rq in refl:
            piece = np.array([idx[tuple(R * Rq)] for R in refl])      # piece r -> piece (r times q)
            emap.append(np.arange(ne) + (piece[r_of] - r_of) * n_piece)
        super().__init__(grid, vmap, np.array(emap), k)

    def _class(self, c):
        """Columns, coefficients and LU factors of the symmetrised system of class c"""
        if c not in self.lu:
            coef = np.array([sign(c, R) for R in self.refl])[:, None] * self.sgn[:, self.rep]
            cols = self.perm[:, self.rep]
            # An orbit on a mirror plane cancels out of some classes
            keep = np.nonzero(np.abs((coef * (cols == self.rep)).sum(axis=0)) > 1e-12)[0]
            cols, coef = np.ascontiguousarray(cols[:, keep]), np.ascontiguousarray(coef[:, keep])
            lu = sla.lu_factor(fold(self.A, keep, cols, coef), overwrite_a=True, check_finite=False)
            self.lu[c] = (keep, cols, coef, lu)
        return self.lu[c]

    def solve(self, d, p, classes=None, b=None):
        """RWG coefficients of the current for the wave p e^{ik d·x}, restricted to the given classes"""
        b, J = (self.trace(d, p) if b is None else b), np.zeros(self.N, complex)
        for c in classes_of(self.k, d, p, self.refl):
            if classes is None or c in classes:
                keep, cols, coef, lu = self._class(c)
                bc = (coef * b[cols]).sum(axis=0) / len(self.refl)      # the part of b of class c, on the orbits
                y = sla.lu_solve(lu, bc, check_finite=False)
                np.add.at(J, cols, coef * y[None, :])
        return J


class Cyclic(Symmetric):
    """
    EFIE on a mesh that a rotation maps to itself (a structured mesh of a body of revolution,
    rotated by one of its G cells). The matrix commutes with the rotations, so the system splits
    into G systems, one for each order q about the axis; the orders that the wave does not
    excite are skipped.
    """
    def solve(self, d, p, tol=1e-12):
        """RWG coefficients of the current for the wave p e^{ik d·x}: one solve for each order q that it excites"""
        G, rep, b = self.G, self.rep, self.trace(d, p)

        # Part of b of each order q, on the orbits
        inv = (G - np.arange(G)) % G
        ix = np.ix_(inv, rep)
        bq = np.fft.fft(self.sgn[ix] * b[self.perm[ix]], axis=0) / G
        size = np.linalg.norm(bq, axis=1)
        J, rows, cols = np.zeros(self.N, complex), np.arange(len(rep)), np.ascontiguousarray(self.perm[:, rep])
        for q in np.nonzero(size > tol * size.max())[0]:
            coef = np.exp(-2j * np.pi * q * np.arange(G) / G)[:, None] * self.sgn[:, rep]
            y = sla.solve(fold(self.A, rows, cols, coef), bq[q], overwrite_a=True, check_finite=False)
            np.add.at(J, cols, coef * y[None, :])
        return J


# The meshes of the paper

def cube_grid(n, g):
    """Graded mesh of the unit cube (n intervals per edge, exponent g), made of one octant and its images"""
    m = int(n) // 2
    s = 0.5 * (1 - (1 - np.arange(m + 1) / m) ** g)
    U, V = [x.ravel() for x in np.meshgrid(s, s, indexing="ij")]
    face = np.column_stack((np.full_like(U, 0.5), U, V))
    verts = np.concatenate([np.roll(face, a, axis=1) for a in range(3)])
    idx = lambda i, j: i * (m + 1) + j
    t0 = []
    for i in range(m):
        for j in range(m):
            t0 += [(idx(i, j), idx(i + 1, j), idx(i + 1, j + 1)), (idx(i, j), idx(i + 1, j + 1), idx(i, j + 1))]
    tris = np.concatenate([np.array(t0) + a * len(face) for a in range(3)])
    refl = group()
    return *mirror_grid(verts, tris, refl), refl


def cube(n, g, k, d, p, pts):
    """
    Unit cube, n intervals per edge graded towards the edges with exponent g, with the three
    mirror planes and the rotation about the body diagonal (four classes at most)
      Returns the field at pts and the number of unknowns of the full mesh
    """
    sym = Mirror(*cube_grid(n, g), k)
    orbit = orbits(classes_of(k, d, p, sym.refl))
    turns = {j: np.linalg.matrix_power(ROT, j) for js in orbit.values() for j in js}
    bs = {j: sym.trace(Q.T @ d, Q.T @ p) for j, Q in turns.items()}
    Js = {j: 0 for j in turns}
    for c, js in orbit.items():                                 # one LU factor in memory at a time
        for j in js:
            Js[j] = Js[j] + sym.solve(turns[j].T @ d, turns[j].T @ p, [c], b=bs[j])
        sym.lu.clear()
    sym.A = None
    return sum(sym.field(J, pts @ turns[j]) @ turns[j].T for j, J in Js.items()), sym.N


def tetrahedron_grid(n, g):
    """Graded three-kite mesh of the regular tetrahedron (n intervals per edge, exponent g), made of F_0 and its D_2 images"""
    m = int(n) // 2
    xi = (np.arange(m + 1) / m) ** g
    U, V = [x.ravel() for x in np.meshgrid(xi, xi, indexing="ij")]
    c0 = FACE0.mean(axis=0)
    idx = lambda i, j: i * (m + 1) + j
    t0 = []
    for i in range(m):
        for j in range(m):
            t0 += [(idx(i, j), idx(i + 1, j), idx(i + 1, j + 1)), (idx(i, j), idx(i + 1, j + 1), idx(i, j + 1))]
    verts, tris = [], []
    for q in range(3):
        A, M1, M2 = FACE0[q], 0.5 * (FACE0[q] + FACE0[(q + 1) % 3]), 0.5 * (FACE0[q] + FACE0[(q + 2) % 3])
        kv = ((1 - U) * (1 - V))[:, None] * A + ((1 - U) * V)[:, None] * M1 + (U * (1 - V))[:, None] * M2 + (U * V)[:, None] * c0
        e1, e2 = kv[t0[0][1]] - kv[t0[0][0]], kv[t0[0][2]] - kv[t0[0][0]]
        tk = np.array(t0) if np.dot(np.cross(e1, e2), -np.ones(3)) > 0 else np.array(t0)[:, [0, 2, 1]]
        tris.append(tk + q * len(kv))
        verts.append(kv)
    return *mirror_grid(np.vstack(verts), np.vstack(tris), TET_REFL), TET_REFL


def tetrahedron(n, g, k, d, p, pts):
    """Regular tetrahedron of unit edge length, with D_2 and the one-third turn about (1, 1, 1) (at most two classes)"""
    sym = Mirror(*tetrahedron_grid(n, g), k)
    orbit = orbits(classes_of(k, d, p, sym.refl))
    turns = {j: np.linalg.matrix_power(ROT, j) for js in orbit.values() for j in js}
    bs = {j: sym.trace(Q.T @ d, Q.T @ p) for j, Q in turns.items()}
    Js = {j: 0 for j in turns}
    for c, js in orbit.items():
        for j in js:
            Js[j] = Js[j] + sym.solve(turns[j].T @ d, turns[j].T @ p, [c], b=bs[j])
        sym.lu.clear()
    sym.A = None
    return sum(sym.field(J, pts @ turns[j]) @ turns[j].T for j, J in Js.items()), sym.N


def torus_grid(R, a, n):
    """Structured mesh of the torus: n cells around the tube, round(n R / a) around the axis"""
    m = int(round(n * R / a))
    T, P = np.meshgrid(2 * np.pi * np.arange(n) / n, 2 * np.pi * np.arange(m) / m, indexing="ij")
    rho = R + a * np.cos(T)
    v = np.stack((rho * np.cos(P), rho * np.sin(P), a * np.sin(T)), axis=0).reshape(3, -1)
    idx = lambda i, j: (i % n) * m + (j % m)
    el = []
    for i in range(n):
        for j in range(m):
            el += [(idx(i, j), idx(i, j + 1), idx(i + 1, j + 1)), (idx(i, j), idx(i + 1, j + 1), idx(i + 1, j))]
    return bempp.Grid(v, np.array(el, dtype=np.uint32).T), m


def torus(n, k, d, p, pts, R=1.0, a=0.5):
    """Torus with the rotational symmetry of its mesh: the rotation by one cell about the axis"""
    grid, m = torus_grid(R, a, n)
    def maps():                                                 # freed in Symmetric.__init__ before assembly
        q = np.arange(m, dtype=np.int32)[:, None]
        i, j = np.divmod(np.arange(n * m, dtype=np.int32), m)
        vmap = i[None, :] * m + (j[None, :] + q) % m           # vertex (i, j) → (i, j + q)
        c = np.arange(n * m, dtype=np.int32)
        return vmap, 2 * vmap[:, np.repeat(c, 2)] + np.tile(np.arange(2, dtype=np.int32), n * m)[None, :]
    sym = Cyclic(grid, *maps(), k)
    J = sym.solve(d, p)
    sym.A = None
    return sym.field(J, pts), sym.N


def almond(n_t, n_s, k, d, p, pts):
    """NASA almond, a structured mesh with n_t cells along and n_s around, with the two mirror planes"""
    q = n_s // 4
    th = np.arange(1, n_t) / n_t * np.pi
    xs = L * (0.5 * (T0 + T1) - 0.5 * (T1 - T0) * np.cos(th))
    phi = np.arange(q + 1) / n_s * 2 * np.pi
    a, b = semi_axes(xs)
    rings = np.stack((np.repeat(xs[:, None], q + 1, 1), a[:, None] * np.cos(phi), b[:, None] * np.sin(phi)), axis=-1).reshape(-1, 3)
    verts = np.concatenate(([[L * T0, 0, 0]], rings, [[L * T1, 0, 0]]))
    verts[np.abs(verts) < 1e-15] = 0.0
    idx = lambda i, j: 1 + i * (q + 1) + j
    last, tris = len(verts) - 1, []
    for j in range(q):                                          # outward normals
        tris += [(0, idx(0, j + 1), idx(0, j)), (last, idx(n_t - 2, j), idx(n_t - 2, j + 1))]
        for i in range(n_t - 2):
            tris += [(idx(i, j), idx(i, j + 1), idx(i + 1, j)), (idx(i, j + 1), idx(i + 1, j + 1), idx(i + 1, j))]
    refl = group((0, 1, 1))
    sym = Mirror(*mirror_grid(verts, np.array(tris), refl), refl, k)
    J = sym.solve(d, p)
    sym.A = None
    return sym.field(J, pts), sym.N
