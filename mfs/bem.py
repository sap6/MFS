    gb = int(0.9 * os.sysconf("SC_PHYS_PAGES") * os.sysconf("SC_PAGE_SIZE") / 2 ** 30)
    os.environ["HWLOC_SYNTHETIC"] = f"node:1(memory={gb}GB) core:{os.cpu_count()} pu:1"

