"""
Boundary element reference and comparison with Bempp-cl (Section 7 and
Appendix C of the paper): the electric field integral equation with RWG
trial and scaled Nédélec test functions, dense LU.

To compare on an equal footing, the boundary element code gets the symmetry
that the MFS uses. The mesh is one piece of the surface and its images under
the symmetry group. A symmetry acts on the RWG coefficients as a signed
permutation, so a current of one symmetry class is a combination of
symmetrised basis functions, one per orbit, and the Galerkin equations need
only the rows of one test function per orbit: an eighth (cube), a quarter
(almond) or 1/G (torus, rotation by one of G cells) of the matrix. The
result is the Galerkin solution of the full mesh, to rounding.

Requires bempp-cl, and pyopencl with a CPU driver for the fast assembly.
"""
import itertools
import os
import time

