"""Bempp with the symmetry of the body, so that the boundary element code
uses the same symmetry as the MFS: any set of coordinate mirror planes
(`Mirror`: three for the cube, two for the almond) or the rotation about
an axis that maps a structured mesh to itself (`Cyclic`: the torus).

The mesh is one fundamental piece (an octant or a quarter of the surface)
and its mirror images. A reflection acts on the RWG coefficients as a signed
permutation T_R. A current of parity class c lies in the span of the
symmetrised functions B_c e_k = sum_R sgn_c(R) T_R e_k, one for each orbit of
degrees of freedom, and the Galerkin equations need to be tested only with
one function per orbit. So only the rows of the EFIE matrix that belong to
the fundamental piece are assembled (a quarter or an eighth of the work),
folded with B_c, and each class is solved by a small LU factorisation. The
result is the Galerkin solution of the full mesh, to rounding.

Used by bem_cube_sym.py, bem_torus.py and fig_cost_almond.py.
"""
import itertools
import time

import bem_env  # noqa: F401  (memory for the OpenCL driver; must come before bempp)
import bempp_cl.api as bempp
import numpy as np
from numba import njit, prange
import scipy.linalg as sla
import scipy.sparse as sp


def group(mirrors=(1, 1, 1)):
    """The reflections generated by the mirrors x -> -x, y -> -y, z -> -z that are switched on."""
    return np.array(list(itertools.product(*[((1.0, -1.0) if on else (1.0,)) for on in mirrors])))


def sign(cls, R):
    return float(np.prod([s for s, r in zip(cls, R) if r < 0]))


def classes_of(d, p, k, refl):
    """The parity classes (sx, sy, sz) that the wave p exp(i k d.x) excites (s = 1 for an axis without mirror)."""
    x = np.random.default_rng(0).uniform(-0.5, 0.5, (40, 3))
    out = []
    for c in sorted({tuple(float(v) for v in r) for r in refl}, reverse=True):     # one class per character of the group
        v = sum(sign(c, R) * (p * R)[None, :] * np.exp(1j * k * ((x * R) @ d))[:, None] for R in refl)
        if np.abs(v).max() > 1e-10:
            out.append(c)
    return out


def mirror_grid(pts, tris, refl):
    """The mesh made of the piece (pts, tris) and its images under the
    reflections. Elements are ordered by reflection: element e of the piece
    has the image e + r * T under reflection number r (T = len(tris)).
    Returns the grid, the vertex maps of the reflections and T."""
    key, verts, elems = {}, [], []
    for R in refl:
        loc = []
        for x in pts * R:
            kk = tuple(np.round(x, 12) + 0.0)
            if kk not in key:
                key[kk] = len(verts)
                verts.append(x)
            loc.append(key[kk])
        t = np.array(loc)[tris]
        elems.append(t if np.prod(R) > 0 else t[:, ::-1])
    verts = np.array(verts)
    vmap = np.array([[key[tuple(np.round(x * R, 12) + 0.0)] for x in verts] for R in refl])
    return bempp.Grid(verts.T, np.concatenate(elems).T.astype(np.uint32)), vmap, len(tris)


def action(space, vmap, emap):
    """Signed permutations of the RWG degrees of freedom under symmetry
    operations of the mesh, given as maps of the vertices (vmap[g, v]) and of
    the elements (emap[g, e]): perm[g, j], sgn[g, j] with T_g e_j = sgn * e_perm."""
    grid = space.grid
    ne, N, ng = grid.number_of_elements, space.global_dof_count, len(vmap)
    el, vt = grid.elements.T, grid.vertices.T
    cen = vt[el].mean(axis=1)
    lc = np.array([[1.0 / 3], [1.0 / 3]])

    def flow(e):
        """For each local function of element e: the local vertex it flows away from, and the sign of that flow."""
        w = space.evaluate(e, lc)[:, :, 0].T               # (3 functions, 3 components)
        dvec = cen[e][None, :] - vt[el[e]]                 # (3 vertices, 3)
        cs = (w @ dvec.T) / (np.linalg.norm(w, axis=1)[:, None] * np.linalg.norm(dvec, axis=1)[None, :])
        v = np.argmax(np.abs(cs), axis=1)
        return v, np.sign(cs[np.arange(3), v])

    # The library's convention is the same on every element: local function l flows away from local vertex
    # vloc[l], with the sign c[l] * local_multipliers. Learn it on one element, check it on a sample.
    mult = np.asarray(space.local_multipliers, float)
    vloc, s0 = flow(0)
    c = s0 * mult[0]
    for e in np.unique(np.linspace(0, ne - 1, 40).astype(int)):
        v, sg = flow(e)
        assert np.array_equal(v, vloc) and np.array_equal(sg, c * mult[e]), "unexpected RWG convention"
    opp, sig = el[:, vloc], c[None, :] * mult
    l2g = space.local2global
    first = np.full(N, ne)
    np.minimum.at(first, l2g, np.arange(ne)[:, None])      # the first element that carries each degree of freedom
    perm = np.zeros((ng, N), np.int64)
    sgn = np.zeros((ng, N))
    j = np.arange(N)
    e = first
    l = np.argmax(l2g[e] == j[:, None], axis=1)
    for q in range(ng):
        e2 = emap[q][e]
        p2 = vmap[q][opp[e, l]]
        l2 = np.argmax(opp[e2] == p2[:, None], axis=1)
        assert np.all(opp[e2, l2] == p2)
        perm[q], sgn[q] = l2g[e2, l2], sig[e, l] * sig[e2, l2]
    return perm, sgn


def reflections(space, vmap, T, refl):
    """The action of the reflections on a mesh made by mirror_grid."""
    ne, nr = space.grid.number_of_elements, len(refl)
    ridx = {tuple(r): i for i, r in enumerate(refl)}
    e = np.arange(ne)
    r_of = e // T                                          # reflection number of the piece the element lies in
    emap = np.array([e + (np.array([ridx[tuple(refl[r] * refl[q])] for r in range(nr)])[r_of] - r_of) * T for q in range(nr)])
    return action(space, vmap, emap)


@bempp.callable(complex=True, parameterized=True)
def class_trace(x, n, domain_index, result, parameters):
    """(part of p exp(i k d.x) with parity (sx, sy, sz)) x n; parameters = (k, d, p, s, which mirrors exist)."""
    e0 = e1 = e2 = 0j
    count = 0.0
    for a in (1.0, -1.0):
        if a < 0 and parameters[10] == 0:
            continue
        for b in (1.0, -1.0):
            if b < 0 and parameters[11] == 0:
                continue
            for c in (1.0, -1.0):
                if c < 0 and parameters[12] == 0:
                    continue
                sg = 1.0 + 0j
                if a < 0:
                    sg = sg * parameters[7]
                if b < 0:
                    sg = sg * parameters[8]
                if c < 0:
                    sg = sg * parameters[9]
                ph = sg * np.exp(1j * parameters[0] * (a * x[0] * parameters[1] + b * x[1] * parameters[2] + c * x[2] * parameters[3]))
                e0 += a * parameters[4] * ph
                e1 += b * parameters[5] * ph
                e2 += c * parameters[6] * ph
                count += 1.0
    e0, e1, e2 = e0 / count, e1 / count, e2 / count
    result[0] = e1 * n[2] - e2 * n[1]
    result[1] = e2 * n[0] - e0 * n[2]
    result[2] = e0 * n[1] - e1 * n[0]


@njit(parallel=True, cache=True)
def fold(A, rows, cols, coef):
    """out[i, k] = sum over the images r of coef[r, k] * A[rows[i], cols[r, k]]."""
    out = np.zeros((len(rows), cols.shape[1]), np.complex128)
    for i in prange(len(rows)):
        a = A[rows[i]]
        for r in range(cols.shape[0]):
            for k in range(cols.shape[1]):
                out[i, k] += coef[r, k] * a[cols[r, k]]
    return out


class Mirror:
    """EFIE on a mirror-symmetric mesh: assembles the rows of the fundamental
    piece once; solve() then returns the current for a plane wave."""

    def __init__(self, grid, vmap, T, refl, k):
        t0 = time.time()
        self.refl, self.k = refl, k
        self.mirrors = [float(np.any(refl[:, i] < 0)) for i in range(3)]
        self.div = div = bempp.function_space(grid, "RWG", 0)
        self.N = N = div.global_dof_count
        self.perm, self.sgn = reflections(div, vmap, T, refl)
        self.rep = rep = np.nonzero(self.perm.min(axis=0) == np.arange(N))[0]       # one degree of freedom per orbit
        l2g = div.local2global
        in_rep = np.zeros(N, bool)
        in_rep[rep] = True
        support = np.nonzero(in_rep[l2g].any(axis=1))[0].astype(np.uint32)
        self.test = test = bempp.function_space(grid, "SNC", 0, support_elements=support, include_boundary_dofs=False)
        full_of = np.full(test.global_dof_count, -1)                    # test function -> degree of freedom of the full space
        tl = test.local2global[support]
        ok = test.local_multipliers[support] != 0                      # local functions that are not degrees of freedom have multiplier 0
        full_of[tl[ok]] = l2g[support][ok]
        rows = np.nonzero(in_rep[full_of])[0]
        self.rows = rows = rows[np.argsort(full_of[rows])]
        assert np.array_equal(full_of[rows], rep)
        t1 = time.time()
        efie = bempp.operators.boundary.maxwell.electric_field(div, div, test, k)
        self.A = np.asarray(efie.weak_form().to_dense())                # (test functions, N)
        self.t_setup, self.t_assembly = t1 - t0, time.time() - t1
        self.lu = {}

    def _class(self, c):
        """Symmetrised basis of class c and the LU factors of its matrix."""
        if c not in self.lu:
            rep, nr = self.rep, len(self.refl)
            sg = np.array([sign(c, R) for R in self.refl])
            B = sp.coo_matrix(((sg[:, None] * self.sgn[:, rep]).ravel(), (self.perm[:, rep].ravel(), np.tile(np.arange(len(rep)), nr))),
                              shape=(self.N, len(rep))).tocsc()
            keep = np.nonzero(np.abs(B).sum(axis=0).A1 > 1e-12)[0]      # orbits on a mirror plane drop out of some classes
            cols = rep[keep]
            Ac = fold(self.A, self.rows[keep], self.perm[:, cols], sg[:, None] * self.sgn[:, cols])   # A[rows[keep]] @ B
            self.lu[c] = (B[:, keep], keep, sla.lu_factor(Ac, overwrite_a=True, check_finite=False))
        return self.lu[c]

    def solve(self, d, p, classes=None):
        """RWG coefficients of the current for the wave p exp(i k d.x)
        (restricted to the given parity classes), and the class sizes."""
        J, sizes = np.zeros(self.N, complex), []
        for c in classes_of(d, p, self.k, self.refl):
            if classes is not None and c not in classes:
                continue
            B, keep, lu = self._class(c)
            par = np.concatenate(([self.k], d, p, c, self.mirrors))
            b = bempp.GridFunction(self.div, fun=class_trace, dual_space=self.test, function_parameters=par).projections(self.test)[self.rows][keep]
            J += B @ sla.lu_solve(lu, b, check_finite=False)
            sizes.append(len(keep))
        return J, sizes

    def field(self, J, points):
        """Scattered field of the current J at the points (n, 3)."""
        lam = bempp.GridFunction(self.div, coefficients=J)
        return -(bempp.operators.potential.maxwell.electric_field(self.div, np.ascontiguousarray(points.T), self.k) * lam).T


@bempp.callable(complex=True, parameterized=True)
def plane_wave_trace(x, n, domain_index, result, parameters):
    """E_inc x n for E_inc = p exp(i k d.x); parameters = (k, d, p)."""
    ph = np.exp(1j * parameters[0] * (x[0] * parameters[1] + x[1] * parameters[2] + x[2] * parameters[3]))
    e0, e1, e2 = parameters[4] * ph, parameters[5] * ph, parameters[6] * ph
    result[0] = e1 * n[2] - e2 * n[1]
    result[1] = e2 * n[0] - e0 * n[2]
    result[2] = e0 * n[1] - e1 * n[0]


class Cyclic:
    """EFIE on a mesh that a rotation maps to itself (a structured mesh of a
    body of revolution: the rotation by one cell about the axis). The
    rotations T_r, r = 0 .. G - 1, act on the RWG coefficients as signed
    permutations, the matrix commutes with them, and the system splits into
    G systems of size N / G, one for each order q about the axis:
    the current of order q is sum_r conj(chi_q(r)) T_r (one function per
    orbit), chi_q(r) = exp(2 pi i q r / G). Only the rows of one function
    per orbit are assembled (1 / G of the work); the orders that the incident
    wave does not excite are skipped."""

    def __init__(self, grid, vmap, emap, k):
        t0 = time.time()
        self.k, self.G = k, len(vmap)
        self.div = div = bempp.function_space(grid, "RWG", 0)
        self.curl = bempp.function_space(grid, "SNC", 0)
        self.N = N = div.global_dof_count
        self.perm, self.sgn = action(div, vmap, emap)
        self.rep = rep = np.nonzero(self.perm.min(axis=0) == np.arange(N))[0]       # one degree of freedom per orbit
        assert len(rep) * self.G == N, "the rotation must not fix any degree of freedom"
        l2g = div.local2global
        in_rep = np.zeros(N, bool)
        in_rep[rep] = True
        support = np.nonzero(in_rep[l2g].any(axis=1))[0].astype(np.uint32)
        self.test = test = bempp.function_space(grid, "SNC", 0, support_elements=support, include_boundary_dofs=False)
        full_of = np.full(test.global_dof_count, -1)
        tl = test.local2global[support]
        ok = test.local_multipliers[support] != 0
        full_of[tl[ok]] = l2g[support][ok]
        rows = np.nonzero(in_rep[full_of])[0]
        self.rows = rows = rows[np.argsort(full_of[rows])]
        assert np.array_equal(full_of[rows], rep)
        t1 = time.time()
        efie = bempp.operators.boundary.maxwell.electric_field(div, div, test, k)
        self.A = np.asarray(efie.weak_form().to_dense())                # (test functions, N)
        self.t_setup, self.t_assembly = t1 - t0, time.time() - t1

    def solve(self, d, p, tol=1e-10):
        """RWG coefficients of the current for the wave p exp(i k d.x), and the orders solved."""
        G, rep = self.G, self.rep
        par = np.concatenate(([self.k], np.asarray(d, float), np.asarray(p, float)))
        b = bempp.GridFunction(self.div, fun=plane_wave_trace, dual_space=self.curl, function_parameters=par).projections(self.curl)
        inv = (G - np.arange(G)) % G
        bq = np.fft.fft(self.sgn[inv][:, rep] * b[self.perm[inv][:, rep]], axis=0) / G      # (order, orbit): part of b of each order
        size = np.linalg.norm(bq, axis=1)
        J, orders = np.zeros(self.N, complex), []
        cols = np.ascontiguousarray(self.perm[:, rep])
        for q in np.nonzero(size > tol * size.max())[0]:
            coef = np.exp(-2j * np.pi * q * np.arange(G) / G)[:, None] * self.sgn[:, rep]
            y = sla.solve(fold(self.A, self.rows, cols, coef), bq[q], overwrite_a=True, check_finite=False)
            np.add.at(J, cols, coef * y[None, :])
            orders.append(int(q))
        return J, orders

    field = Mirror.field
